# Road class base risk / traffic multiplier
ROAD_CLASS_WEIGHTS = {
    "motorway": 2.2,
    "trunk": 2.0,
    "primary": 1.7,
    "secondary": 1.4,
    "tertiary": 1.15,
    "residential": 0.8,
    "living_street": 0.6,
    "service": 0.5,
    "unclassified": 0.7,
}


def calculate_hotspot_multiplier(
    lats: np.ndarray,
    lons: np.ndarray,
    highways: np.ndarray,
) -> np.ndarray:
    """Identify key accident corridors in Nagpur and apply a 3.0x - 6.0x multiplier.

    Corridors:
    - Sitabuldi central intersection & transit hub (3.5x)
    - Wardha Road spine (south from Sitabuldi past Ajni & Somalwada towards Khapri) (4.5x)
    - Medical Square / GMC corridor (3.2x)
    - Sadar commercial corridor (3.0x)
    - Amravati Road arterial (4.0x)
    - Hingna Road industrial corridor (3.5x)
    - Outer Ring Road & Expressways (5.0x)
    """
    multipliers = np.ones(len(lats), dtype=float)

    # 1. Sitabuldi Hub (approx 21.140 - 21.152 N, 79.080 - 79.095 E)
    is_sitabuldi = (lats >= 21.140) & (lats <= 21.152) & (lons >= 79.080) & (lons <= 79.095)
    multipliers[is_sitabuldi] = np.maximum(multipliers[is_sitabuldi], 3.5)

    # 2. Wardha Road corridor (approx 21.060 - 21.135 N, 79.065 - 79.088 E)
    is_wardha_rd = (lats >= 21.060) & (lats <= 21.135) & (lons >= 79.065) & (lons <= 79.088)
    multipliers[is_wardha_rd] = np.maximum(multipliers[is_wardha_rd], 4.5)

    # 3. Medical Square (approx 21.128 - 21.142 N, 79.095 - 79.112 E)
    is_medical_sq = (lats >= 21.128) & (lats <= 21.142) & (lons >= 79.095) & (lons <= 79.112)
    multipliers[is_medical_sq] = np.maximum(multipliers[is_medical_sq], 3.2)

    # 4. Sadar corridor (approx 21.155 - 21.170 N, 79.075 - 79.092 E)
    is_sadar = (lats >= 21.155) & (lats <= 21.170) & (lons >= 79.075) & (lons <= 79.092)
    multipliers[is_sadar] = np.maximum(multipliers[is_sadar], 3.0)

    # 5. Amravati Road (approx 21.145 - 21.162 N, 79.000 - 79.065 E)
    is_amravati_rd = (lats >= 21.145) & (lats <= 21.162) & (lons >= 79.000) & (lons <= 79.065)
    multipliers[is_amravati_rd] = np.maximum(multipliers[is_amravati_rd], 4.0)

    # 6. Hingna Road (approx 21.080 - 21.120 N, 78.980 - 79.050 E)
    is_hingna_rd = (lats >= 21.080) & (lats <= 21.120) & (lons >= 78.980) & (lons <= 79.050)
    multipliers[is_hingna_rd] = np.maximum(multipliers[is_hingna_rd], 3.5)

    # 7. Motorways & Trunks (Outer Ring Road / bypasses)
    is_trunk_motorway = np.isin(highways, ["motorway", "trunk"])
    multipliers[is_trunk_motorway] = np.maximum(multipliers[is_trunk_motorway], 4.0)

    return multipliers


def calculate_traffic_proxy(segments: pd.DataFrame) -> np.ndarray:
    """Calculate composite traffic density proxy from road class, population, built-up, POIs, and night lights."""
    n = len(segments)

    # Road class factor
    hwy_factor = np.array([
        ROAD_CLASS_WEIGHTS.get(str(h).lower(), 0.8)
        for h in segments["highway"]
    ])

    # Lanes factor
    lanes = segments["lanes"].values.astype(float)
    lanes_factor = 1.0 + 0.15 * np.clip(lanes - 1, 0, 5)

    # Population density factor (normalized)
    pop = segments["population_density"].values.astype(float)
    pop_norm = np.clip(pop / 150.0, 0.1, 3.0)
    pop_factor = 0.7 + 0.5 * pop_norm

    # Built-up factor
    built = segments["built_up"].values.astype(float)
    built_factor = 0.6 + 0.7 * np.clip(built, 0.0, 1.0)

    # POI density factor
    schools = segments["schools"].values.astype(float) if "schools" in segments else np.zeros(n)
    markets = segments["markets"].values.astype(float) if "markets" in segments else np.zeros(n)
    bus_stops = segments["bus_stops"].values.astype(float) if "bus_stops" in segments else np.zeros(n)
    signals = segments["signals"].values.astype(float) if "signals" in segments else np.zeros(n)

    poi_factor = (
        1.0
        + 0.08 * np.minimum(schools, 3)
        + 0.06 * np.minimum(markets, 3)
        + 0.04 * np.minimum(bus_stops, 5)
        + 0.05 * np.minimum(signals, 2)
    )

    # Night lights percentile factor
    ntl_pct = segments["ntl_percentile"].values.astype(float) if "ntl_percentile" in segments else np.full(n, 0.5)
    ntl_factor = 0.8 + 0.4 * ntl_pct

    # Composite proxy
    traffic_proxy = hwy_factor * lanes_factor * pop_factor * built_factor * poi_factor * ntl_factor
    return traffic_proxy


def sample_nagpur_conditions(
    n_events: int,
    rng: np.random.Generator,
) -> Tuple[np.ndarray, np.ndarray, np.ndarray, np.ndarray, np.ndarray, np.ndarray]:
    """Sample month, hour, weather, light, surface, and visibility according to Nagpur meteorological rules."""
    # 1. Month (uniform across calendar year)
    months = rng.integers(1, 13, size=n_events)

    # 2. Hour with Nagpur traffic diurnal pattern:
    # Morning commute peak: 08:00 - 10:00 (weight 1.8)
    # Evening commute peak: 17:00 - 20:00 (weight 2.2)
    # Daytime: 10:00 - 17:00 (weight 1.2)
    # Early morning: 05:00 - 08:00 (weight 0.8)
    # Night: 21:00 - 05:00 (weight 0.5, fewer crashes overall)
    hour_weights = np.array([
        0.4, 0.3, 0.3, 0.3, 0.4,       # 00:00 - 04:00 (late night)
        0.8, 1.0, 1.4,                 # 05:00 - 07:00 (early morning)
        1.8, 2.0,                      # 08:00 - 09:00 (morning peak)
        1.2, 1.1, 1.2, 1.2, 1.3, 1.4,  # 10:00 - 15:00 (midday)
        1.6,                           # 16:00
        2.2, 2.4, 2.2, 2.0,            # 17:00 - 20:00 (evening peak)
        1.2, 0.7, 0.5,                 # 21:00 - 23:00 (night)
    ], dtype=float)
    hour_probs = hour_weights / hour_weights.sum()
    hours = rng.choice(np.arange(24), size=n_events, p=hour_probs)

    # 3. Weather based on Nagpur climate seasons
    weathers = np.empty(n_events, dtype=object)

    # Monsoon: Jun-Sep (months 6, 7, 8, 9) -> rain 45%, storm 10%, clear 45%
    monsoon_mask = np.isin(months, [6, 7, 8, 9])
    if np.any(monsoon_mask):
        weathers[monsoon_mask] = rng.choice(
            ["clear", "rain", "storm"],
            size=int(np.sum(monsoon_mask)),
            p=[0.45, 0.45, 0.10],
        )

    # Winter: Oct-Feb (months 10, 11, 12, 1, 2)
    # Fog (10%) occurs STRICTLY between 05:00 and 08:00. Outside this window, fog is 0%.
    winter_mask = np.isin(months, [10, 11, 12, 1, 2])
    winter_fog_window = winter_mask & np.isin(hours, [5, 6, 7, 8])
    if np.any(winter_fog_window):
        weathers[winter_fog_window] = rng.choice(
            ["clear", "fog", "rain"],
            size=int(np.sum(winter_fog_window)),
            p=[0.88, 0.10, 0.02],
        )

    winter_other = winter_mask & ~winter_fog_window
    if np.any(winter_other):
        weathers[winter_other] = rng.choice(
            ["clear", "rain"],
            size=int(np.sum(winter_other)),
            p=[0.97, 0.03],
        )

    # Summer: Mar-May (months 3, 4, 5) -> mostly clear
    summer_mask = np.isin(months, [3, 4, 5])
    if np.any(summer_mask):
        weathers[summer_mask] = rng.choice(
            ["clear", "rain", "storm"],
            size=int(np.sum(summer_mask)),
            p=[0.95, 0.04, 0.01],
        )

    # 4. Surface Condition (ensuring physical realism)
    # In rain/storm, surface is wet. Never dry!
    surfaces = np.empty(n_events, dtype=object)
    wet_weather = np.isin(weathers, ["rain", "storm"])
    surfaces[wet_weather] = "wet"

    fog_weather = (weathers == "fog")
    if np.any(fog_weather):
        surfaces[fog_weather] = rng.choice(["wet", "dry"], size=int(np.sum(fog_weather)), p=[0.5, 0.5])

    clear_weather = (weathers == "clear")
    if np.any(clear_weather):
        surfaces[clear_weather] = rng.choice(["dry", "wet"], size=int(np.sum(clear_weather)), p=[0.98, 0.02])

    # 5. Light (Daylight vs Dark)
    # In Nagpur (latitude ~21 N), daylight is approximately 06:00 to 18:00
    is_night = ((hours < 6) | (hours >= 19)).astype(int)
    light_condition = np.where(is_night == 1, "dark", "daylight")

    # 6. Visibility in km
    visibilities = np.empty(n_events, dtype=float)
    visibilities[weathers == "clear"] = rng.uniform(8.0, 10.0, size=int(np.sum(weathers == "clear")))
    visibilities[weathers == "rain"] = rng.uniform(2.0, 5.0, size=int(np.sum(weathers == "rain")))
    visibilities[weathers == "storm"] = rng.uniform(0.5, 2.0, size=int(np.sum(weathers == "storm")))
    visibilities[weathers == "fog"] = rng.uniform(0.1, 0.8, size=int(np.sum(weathers == "fog")))

    # Assertions for impossible weather combinations
    assert not ((weathers == "fog") & (np.isin(months, [6, 7, 8, 9]) | (hours > 8) | (hours < 5))).any(), (
        "Assertion failed: Impossible fog event detected outside 05:00-08:00 winter window."
    )
    assert not (np.isin(weathers, ["rain", "storm"]) & (surfaces == "dry")).any(), (
        "Assertion failed: Rain or storm occurred with dry road surface."
    )

    return months, hours, weathers, light_condition, surfaces, visibilities


def generate_accidents(
    target_count: Optional[int] = None,
    input_features_path: Optional[Path] = None,
    output_path: Optional[Path] = None,
) -> pd.DataFrame:
    """Generate synthetic accident dataset."""
    in_path = input_features_path or (DATA_DIR / "segments_features.parquet")
    out_path = output_path or (DATA_DIR / "synthetic_accidents.parquet")

    if not in_path.exists():
        raise FileNotFoundError(f"Feature dataset not found at {in_path}. Run Stage 2 first.")

    print(f"Loading Stage 2 features from: {in_path}")
    segments = gpd.read_parquet(in_path)
    n_segments = len(segments)
    print(f"Loaded {n_segments:,} enriched road segments.")

    # Determine desired total event count: ~50k for test area, ~1m for full city
    if target_count is None:
        target_count = 50_000 if len(segments) < 50_000 else 1_000_000

    print(f"Targeting approximately {target_count:,} synthetic accident events...")
    rng = np.random.default_rng(RANDOM_SEED)

    # 1. Calculate Traffic Proxy & Hotspots
    traffic_proxy = calculate_traffic_proxy(segments)
    hotspot_mult = calculate_hotspot_multiplier(
        segments["centroid_lat"].values,
        segments["centroid_lon"].values,
        segments["highway"].values,
    )

    # 2. Poisson expected counts per segment
    junction_count = segments["junction_count"].values.astype(float)
    curvature = segments["curvature"].values.astype(float)
    length_m = segments["length_m"].values.astype(float)
    length_factor = np.clip(length_m / 150.0, 0.1, 2.0)

    raw_rates = traffic_proxy * (1.0 + 0.15 * junction_count + 0.5 * curvature) * hotspot_mult * length_factor
    base_rate = target_count / np.sum(raw_rates)
    expected_accidents = base_rate * raw_rates

    # Sample Poisson accident occurrences per segment
    sampled_counts = rng.poisson(expected_accidents)
    total_generated = int(np.sum(sampled_counts))
    print(f"Simulated {total_generated:,} total accident events across {n_segments:,} segments.")

    # Expand segments by event counts
    road_indices = np.repeat(np.arange(n_segments), sampled_counts)
    events = segments.iloc[road_indices].copy().reset_index(drop=True)

    # 3. Sample meteorological and temporal conditions
    months, hours, weathers, lights, surfaces, visibilities = sample_nagpur_conditions(
        total_generated,
        rng,
    )

    events["event_id"] = [f"SYN-NGP-{i + 1:07d}" for i in range(total_generated)]
    events["is_synthetic"] = True
    events["month"] = months
    events["hour"] = hours
    events["day_of_week"] = rng.integers(0, 7, size=total_generated)
    events["weather"] = weathers
    events["light"] = lights
    events["surface_condition"] = surfaces
    events["visibility_km"] = visibilities

    # Night flag
    is_night = ((hours < 6) | (hours >= 19)).astype(int)
    events["is_night"] = is_night

    # Dark exposure = is_night * (1 - ntl_percentile)
    ntl_pct = events["ntl_percentile"].values.astype(float)
    events["dark_exposure"] = is_night * (1.0 - ntl_pct)

    # 4. Vehicle speed simulation (correlated with road maxspeed, night, and weather)
    base_maxspeed = events["maxspeed"].values.astype(float)
    # Late night speed increase (+5-10 km/h on clear roads) vs adverse weather speed decrease (-5-12 km/h)
    speed_delta = (
        rng.normal(0.0, 5.0, size=total_generated)
        + 6.0 * is_night
        - 8.0 * np.isin(weathers, ["rain", "storm"]).astype(float)
        - 12.0 * (weathers == "fog").astype(float)
    )
    vehicle_speed = np.clip(base_maxspeed + speed_delta, 15.0, 120.0)
    events["vehicle_speed"] = vehicle_speed

    # 5. Continuous Severity Risk Formulation
    # risk = 0.02*(vehicle_speed-50) + 1.2*curvature + 0.25*junction_count
    #        + 0.8*rain + 1.2*fog + 1.0*storm + 0.7*night + 0.5*dark_exposure
    #        + 0.3*(slope>3) + 0.4*school_zone + Normal(0, 0.6)
    is_rain = (weathers == "rain").astype(float)
    is_fog = (weathers == "fog").astype(float)
    is_storm = (weathers == "storm").astype(float)
    slope_gt3 = (events["slope"].values.astype(float) > 3.0).astype(float)
    school_zone_val = events["school_zone"].values.astype(float)

    latent_risk = (
        0.02 * (vehicle_speed - 50.0)
        + 1.2 * events["curvature"].values.astype(float)
        + 0.25 * events["junction_count"].values.astype(float)
        + 0.8 * is_rain
        + 1.2 * is_fog
        + 1.0 * is_storm
        + 0.7 * is_night
        + 0.5 * events["dark_exposure"].values.astype(float)
        + 0.3 * slope_gt3
        + 0.4 * school_zone_val
        + rng.normal(0.0, 0.6, size=total_generated)
    )
    events["latent_risk"] = latent_risk

    # Tune thresholds to achieve ~60% minor, ~30% serious, ~10% fatal
    th_minor = np.quantile(latent_risk, 0.60)
    th_serious = np.quantile(latent_risk, 0.90)

    severity = np.where(latent_risk < th_minor, "minor", np.where(latent_risk < th_serious, "serious", "fatal"))

    # Add 5% label noise (randomly swap with adjacent class)
    noise_mask = rng.random(total_generated) < 0.05
    n_noisy = int(np.sum(noise_mask))
    if n_noisy > 0:
        flip_choices = rng.choice(["minor", "serious", "fatal"], size=n_noisy, p=[0.60, 0.30, 0.10])
        severity[noise_mask] = flip_choices

    events["severity"] = severity

    # Final columns to save
    output_columns = [
        "event_id",
        "segment_id",
        "severity",
        "is_synthetic",
        "month",
        "hour",
        "day_of_week",
        "weather",
        "light",
        "surface_condition",
        "visibility_km",
        "vehicle_speed",
        "is_night",
        "dark_exposure",
        "highway",
        "length_m",
        "lanes",
        "maxspeed",
        "curvature",
        "junction_count",
        "elevation",
        "slope",
        "built_up",
        "population_density",
        "night_lights",
        "ntl_percentile",
        "ntl_gradient",
        "lit_tag",
        "schools",
        "markets",
        "bus_stops",
        "signals",
        "school_zone",
        "is_market_zone",
        "centroid_lat",
        "centroid_lon",
    ]
    df_to_save = events[output_columns].copy()

    # Save to primary data/synthetic_accidents.parquet
    df_to_save.to_parquet(out_path, index=False)

    # Also save copy to data/synthetic_accident_events.parquet for full repo interoperability
    compat_path = DATA_DIR / "synthetic_accident_events.parquet"
    df_to_save.to_parquet(compat_path, index=False)

    # Print summary statistics
    class_counts = df_to_save["severity"].value_counts()
    class_pcts = df_to_save["severity"].value_counts(normalize=True) * 100.0

    print("\n================ STAGE 3: SYNTHETIC ACCIDENTS SUMMARY ================")
    print(f"Total Synthetic Events: {total_generated:,}")
    print("\nClass Balance:")
    for cls in ["minor", "serious", "fatal"]:
        cnt = class_counts.get(cls, 0)
        pct = class_pcts.get(cls, 0.0)
        print(f"  {cls.capitalize():<8}: {cnt:,} ({pct:.2f}%)")

    print("\nTop 20 Road Segments by Incident Frequency:")
    top_segs = df_to_save["segment_id"].value_counts().head(20)
    top_seg_meta = segments[segments["segment_id"].isin(top_segs.index)].set_index("segment_id")
    for rank, (sid, count) in enumerate(top_segs.items(), 1):
        meta = top_seg_meta.loc[sid] if sid in top_seg_meta.index else None
        hwy = meta["highway"] if meta is not None else "unknown"
        spd = meta["maxspeed"] if meta is not None else "?"
        print(f"  {rank:2d}. Segment #{sid:<6} | Events: {count:3d} | Class: {hwy:<12} | Speed: {spd} km/h")

    print(f"\nSaved successfully to: {out_path} and {compat_path}")
    print("=====================================================================\n")

    return df_to_save


def main():
    generate_accidents()


if __name__ == "__main__":
    main()
